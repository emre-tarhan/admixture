package models

import (
	"bufio"
	"bytes"
	"fmt"
	"io"
	"sort"
	"strconv"
	"strings"
	"sync"
)

// Coord holds reference-build coordinates for a model SNP.
//
// Model allele files only carry rsIDs, but VCF/gVCF input (unlike vendor
// raw exports) usually has no rsID annotations — matching then happens by
// chromosomal position, which is build-specific. positions.tsv therefore
// stores each model SNP's position on both major reference builds plus the
// expected reference allele, letting the tool match VCF input on either
// build without the user having to pick one.
type Coord struct {
	RsID  string
	Chrom string // canonical: 1-22, X, Y, M
	Pos19 int    // hg19 position (1-based); 0 = unknown
	Pos38 int    // hg38 position (1-based); 0 = unknown
	Ref   byte   // expected reference allele (forward strand); 0 = unknown
}

// posRef is one coordinate key inside a Wanted set's range index.
type posRef struct {
	Pos int
	Ref byte
	Key string // full lookup key, e.g. "hg38:1:759036"
}

// Wanted is the set of lookup keys a VCF/gVCF parser should extract for a
// selection of models. Keys maps a lookup key ("rs123" or
// "hgNN:chrom:pos") to the expected reference allele (0 when unknown);
// ranges indexes the coordinate keys per build+chromosome so that gVCF
// reference blocks can be expanded by position span.
type Wanted struct {
	Keys   map[string]byte
	ranges map[string][]posRef // "hg19:1" -> sorted by Pos
}

// Lookup returns the expected reference allele for a key (0 if unknown or
// absent).
func (w *Wanted) Lookup(key string) (byte, bool) {
	if w == nil {
		return 0, false
	}
	ref, ok := w.Keys[key]
	return ref, ok
}

// Expand returns every wanted coordinate whose position lies in
// [start, end] on the given build and chromosome, ordered by position.
func (w *Wanted) Expand(build, chrom string, start, end int) []posRef {
	if w == nil {
		return nil
	}
	list := w.ranges[build+":"+chrom]
	lo := sortSearchPos(list, start)
	out := make([]posRef, 0, 4)
	for ; lo < len(list) && list[lo].Pos <= end; lo++ {
		out = append(out, list[lo])
	}
	return out
}

func sortSearchPos(list []posRef, pos int) int {
	lo, hi := 0, len(list)
	for lo < hi {
		mid := (lo + hi) / 2
		if list[mid].Pos < pos {
			lo = mid + 1
		} else {
			hi = mid
		}
	}
	return lo
}

// coordKey formats a lookup key for a positional match.
func coordKey(build, chrom string, pos int) string {
	return build + ":" + chrom + ":" + strconv.Itoa(pos)
}

// coordFile is the embedded coordinate index, generated by cmd/snpindex
// from UCSC snp151Common tables (dbSNP build 151).
const coordFile = "data/positions.tsv"

var (
	coordsOnce sync.Once
	coordsMap  map[string]*Coord
)

// coordFor returns the coordinate record for an rsID, or nil when the
// embedded index has no entry for it.
func coordFor(rsID string) *Coord {
	coordsOnce.Do(loadCoords)
	return coordsMap[rsID]
}

// loadCoords parses the embedded data/positions.tsv:
//
//	rsID<TAB>chrom<TAB>pos19<TAB>pos38<TAB>ref
//
// Positions and ref may be "." when unknown. See cmd/snpindex for how the
// file is generated.
func loadCoords() {
	f, err := content.Open(coordFile)
	if err != nil {
		return // index absent: models degrade to rsID-only matching
	}
	defer func() { _ = f.Close() }()
	coordsMap = parseCoords(f)
}

func parseCoords(r io.Reader) map[string]*Coord {
	m := make(map[string]*Coord, 256<<10)
	scanner := bufio.NewScanner(r)
	scanner.Buffer(make([]byte, 0, 64<<10), 1<<20)
	for scanner.Scan() {
		line := scanner.Text()
		if line == "" || strings.HasPrefix(line, "#") {
			continue
		}
		parts := strings.Split(line, "\t")
		if len(parts) < 5 || !strings.HasPrefix(parts[0], "rs") {
			continue
		}
		c := &Coord{RsID: parts[0], Chrom: parts[1]}
		c.Pos19, _ = strconv.Atoi(parts[2])
		c.Pos38, _ = strconv.Atoi(parts[3])
		if len(parts[4]) == 1 && isBase(parts[4][0]) {
			c.Ref = parts[4][0]
		}
		m[c.RsID] = c
	}
	return m
}

func isBase(b byte) bool {
	switch b {
	case 'A', 'C', 'G', 'T':
		return true
	}
	return false
}

// Key returns the positional lookup key for this coordinate on the given
// build ("hg19"/"hg38"), e.g. "hg38:1:759036".
func (c *Coord) Key(build string) string {
	pos := c.Pos38
	if build == "hg19" {
		pos = c.Pos19
	}
	return build + ":" + c.Chrom + ":" + strconv.Itoa(pos)
}

// BuildWanted unions the lookup keys of the given models into a Wanted set
// for the VCF parser.
func BuildWanted(models []*Model) *Wanted {
	w := &Wanted{
		Keys:   make(map[string]byte, 1<<20),
		ranges: make(map[string][]posRef),
	}
	for _, m := range models {
		for i, snp := range m.SNPs {
			if _, ok := w.Keys[snp]; !ok {
				w.Keys[snp] = 0
			}
			if i >= len(m.Coords) {
				continue
			}
			c := m.Coords[i]
			if c == nil {
				continue
			}
			if c.Pos38 > 0 {
				addWantedKey(w, "hg38", c, c.Pos38)
			}
			if c.Pos19 > 0 {
				addWantedKey(w, "hg19", c, c.Pos19)
			}
		}
	}
	for _, list := range w.ranges {
		sort.Slice(list, func(i, j int) bool { return list[i].Pos < list[j].Pos })
	}
	return w
}

func addWantedKey(w *Wanted, build string, c *Coord, pos int) {
	key := coordKey(build, c.Chrom, pos)
	if _, ok := w.Keys[key]; !ok {
		w.Keys[key] = c.Ref
	}
	id := build + ":" + c.Chrom
	w.ranges[id] = append(w.ranges[id], posRef{Pos: pos, Ref: c.Ref, Key: key})
}

// parseCoordsFromLines is a helper used by tests to build an index from
// literal lines.
func parseCoordsFromLines(lines ...string) map[string]*Coord {
	var b bytes.Buffer
	for _, l := range lines {
		fmt.Fprintln(&b, l)
	}
	return parseCoords(&b)
}
