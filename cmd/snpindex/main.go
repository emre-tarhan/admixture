// Command snpindex builds the SNP coordinate index (positions.tsv) that
// pkg/models embeds for position-based VCF/gVCF matching.
//
// It cross-references the rsIDs found in the model allele files with UCSC
// dbSNP tables (snp151Common for both hg19 and hg38) and emits one line per
// model SNP:
//
//	rsID  chrom  pos19  pos38  ref
//
// Download the inputs from:
//
//	https://hgdownload.soe.ucsc.edu/goldenPath/hg38/database/snp151Common.txt.gz
//	https://hgdownload.soe.ucsc.edu/goldenPath/hg19/database/snp151Common.txt.gz
//
// Example:
//
//	go run ./cmd/snpindex \
//	  -alleles 'pkg/models/data/*.alleles' \
//	  -hg38 snp151Common_hg38.txt.gz \
//	  -hg19 snp151Common_hg19.txt.gz \
//	  -out pkg/models/data/positions.tsv
package main

import (
	"bufio"
	"compress/gzip"
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"
)

func main() {
	allelesGlob := flag.String("alleles", "pkg/models/data/*.alleles", "glob of model allele files")
	hg19Path := flag.String("hg19", "", "UCSC snp151Common.txt.gz for hg19 (optional)")
	hg38Path := flag.String("hg38", "", "UCSC snp151Common.txt.gz for hg38 (optional)")
	outPath := flag.String("out", "pkg/models/data/positions.tsv", "output index file")
	flag.Parse()

	if *hg19Path == "" && *hg38Path == "" {
		fmt.Fprintln(os.Stderr, "at least one of -hg19/-hg38 is required")
		os.Exit(2)
	}

	// 1. Union of model rsIDs, preserving first-seen order.
	rsids, known, perModel, err := loadModelRsIDs(*allelesGlob)
	if err != nil {
		fail(err)
	}
	fmt.Printf("Model SNPs: %d unique rsIDs across %d models\n", len(rsids), len(perModel))

	// rsID -> canonical info from the UCSC tables. Only model rsIDs get a
	// row: the UCSC tables hold ~15M entries each and materializing all of
	// them would exhaust memory. Each build keeps its own hit so an alt
	// contig cannot overwrite the primary chromosome.
	seen := make(map[string]*snpRow, len(rsids))
	get := func(rsid string) *snpRow {
		r, ok := seen[rsid]
		if !ok {
			r = &snpRow{}
			seen[rsid] = r
		}
		return r
	}

	// 2. Scan the UCSC tables, keeping only model rsIDs.
	if *hg19Path != "" {
		n, err := scanUCSC(*hg19Path, known, func(rsid, chrom string, pos int, ref byte) {
			get(rsid).hg19.set(chrom, pos, ref)
		})
		if err != nil {
			fail(err)
		}
		fmt.Printf("hg19 table: scanned %d rows\n", n)
	}
	if *hg38Path != "" {
		n, err := scanUCSC(*hg38Path, known, func(rsid, chrom string, pos int, ref byte) {
			get(rsid).hg38.set(chrom, pos, ref)
		})
		if err != nil {
			fail(err)
		}
		fmt.Printf("hg38 table: scanned %d rows\n", n)
	}

	// 3. Write the index and report coverage.
	out, err := os.Create(*outPath)
	if err != nil {
		fail(err)
	}
	defer func() {
		if err := out.Close(); err != nil {
			fail(err)
		}
	}()
	fmt.Fprintln(out, "# rsID\tchrom\tpos19\tpos38\tref — generated by cmd/snpindex from UCSC snp151Common (dbSNP b151); see docs/models.md")

	var with19, with38, withRef, written int
	for _, rsid := range rsids {
		r := seen[rsid]
		if r == nil {
			continue
		}
		chrom, pos19, pos38, ref, ok := r.fields()
		if !ok {
			continue
		}
		p19, p38, refS := ".", ".", "."
		if pos19 > 0 {
			p19 = fmt.Sprint(pos19)
			with19++
		}
		if pos38 > 0 {
			p38 = fmt.Sprint(pos38)
			with38++
		}
		if ref != 0 {
			refS = string(ref)
			withRef++
		}
		fmt.Fprintf(out, "%s\t%s\t%s\t%s\t%s\n", rsid, chrom, p19, p38, refS)
		written++
	}

	fmt.Printf("Index: %d SNPs written to %s\n", written, *outPath)
	fmt.Printf("Coverage: hg19 %.2f%%  hg38 %.2f%%  ref allele %.2f%%\n",
		pct(with19, len(rsids)), pct(with38, len(rsids)), pct(withRef, len(rsids)))

	for _, pm := range perModel {
		fmt.Printf("  %-18s %7d SNPs\n", pm.name, pm.total)
	}
}

func pct(n, d int) float64 {
	if d == 0 {
		return 0
	}
	return 100 * float64(n) / float64(d)
}

// asmHit is one build's chosen mapping for an rsID. A primary-chromosome
// hit (1–22, X, Y, M) is kept in preference to a later alt-contig row.
type asmHit struct {
	chrom   string
	pos     int
	ref     byte
	primary bool
}

func (h *asmHit) set(chrom string, pos int, ref byte) {
	prim := isPrimaryChrom(chrom)
	if h.pos > 0 && h.primary && !prim {
		return
	}
	h.chrom, h.pos, h.primary = chrom, pos, prim
	if ref != 0 {
		h.ref = ref
	}
}

func isPrimaryChrom(chrom string) bool {
	switch chrom {
	case "X", "Y", "M":
		return true
	}
	n := 0
	for _, c := range chrom {
		if c < '0' || c > '9' {
			return false
		}
		n = n*10 + int(c-'0')
	}
	return n >= 1 && n <= 22
}

type snpRow struct {
	hg19, hg38 asmHit
}

// fields returns the index columns. Alt-contig-only hits are dropped.
// When the two builds name different primary chromosomes, each coordinate
// is kept only when its chromosome matches the one written (hg38 wins).
func (r *snpRow) fields() (chrom string, pos19, pos38 int, ref byte, ok bool) {
	c19, p19, ok19 := usable(r.hg19)
	c38, p38, ok38 := usable(r.hg38)
	if !ok19 && !ok38 {
		return "", 0, 0, 0, false
	}
	chrom = c38
	if chrom == "" {
		chrom = c19
	}
	if ok19 && c19 == chrom {
		pos19 = p19
	}
	if ok38 && c38 == chrom {
		pos38 = p38
	}
	if ok38 && r.hg38.ref != 0 {
		ref = r.hg38.ref
	} else {
		ref = r.hg19.ref
	}
	return chrom, pos19, pos38, ref, true
}

func usable(h asmHit) (string, int, bool) {
	if h.pos > 0 && h.primary {
		return h.chrom, h.pos, true
	}
	return "", 0, false
}

type modelInfo struct {
	name   string
	total  int
	rsfile map[string]bool
}

func loadModelRsIDs(glob string) ([]string, map[string]bool, map[string]*modelInfo, error) {
	files, err := filepath.Glob(glob)
	if err != nil {
		return nil, nil, nil, err
	}
	if len(files) == 0 {
		return nil, nil, nil, fmt.Errorf("no allele files match %q", glob)
	}
	var order []string
	union := make(map[string]bool, 512<<10)
	perModel := map[string]*modelInfo{}
	sort.Strings(files)
	for _, f := range files {
		name := strings.TrimSuffix(filepath.Base(f), ".alleles")
		mi := &modelInfo{name: name, rsfile: map[string]bool{}}
		file, err := os.Open(f)
		if err != nil {
			return nil, nil, nil, err
		}
		scanner := bufio.NewScanner(file)
		scanner.Buffer(make([]byte, 0, 64<<10), 1<<20)
		for scanner.Scan() {
			parts := strings.Fields(scanner.Text())
			if len(parts) < 3 {
				continue
			}
			mi.total++
			if !union[parts[0]] {
				union[parts[0]] = true
				order = append(order, parts[0])
			}
		}
		if err := file.Close(); err != nil {
			return nil, nil, nil, err
		}
		perModel[name] = mi
	}
	return order, union, perModel, nil
}

// scanUCSC streams a snp151Common.txt.gz (UCSC MySQL dump) and calls fn for
// every single-base SNP whose rsID exists in the known (model union) set.
// Rows outside the set are discarded immediately — the tables hold ~15M
// entries each, and materializing them all would exhaust memory.
func scanUCSC(path string, known map[string]bool, fn func(rsid, chrom string, pos int, ref byte)) (int, error) {
	file, err := os.Open(path)
	if err != nil {
		return 0, err
	}
	defer func() { _ = file.Close() }()
	gz, err := gzip.NewReader(file)
	if err != nil {
		return 0, err
	}
	defer func() { _ = gz.Close() }()

	scanner := bufio.NewScanner(gz)
	scanner.Buffer(make([]byte, 0, 256<<10), 4<<20)
	var rows int
	for scanner.Scan() {
		line := scanner.Text()
		rows++
		// 1 bin, 2 chrom, 3 chromStart, 4 chromEnd, 5 name, 8 refNCBI, 12 class
		fields := strings.Split(line, "\t")
		if len(fields) < 12 {
			continue
		}
		if fields[11] != "single" {
			continue
		}
		rsid := fields[4]
		if !strings.HasPrefix(rsid, "rs") {
			continue
		}
		chrom := strings.TrimPrefix(fields[1], "chr")
		if chrom == "" {
			continue
		}
		start := 0
		for _, c := range []byte(fields[2]) {
			if c < '0' || c > '9' {
				start = 0
				break
			}
			start = start*10 + int(c-'0')
		}
		if start <= 0 {
			continue
		}
		var ref byte
		if len(fields[7]) == 1 && fields[7] != "-" {
			ref = fields[7][0]
		}
		if known[rsid] {
			fn(rsid, chrom, start+1, ref)
		}
	}
	return rows, scanner.Err()
}

func fail(err error) {
	fmt.Fprintln(os.Stderr, "snpindex:", err)
	os.Exit(1)
}
